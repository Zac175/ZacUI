-- Maps_Data - the map datasets: unexplored overlay tiles, map pin
-- positions and zone level ranges.
-- Part of ZacUI; load order is set by the TOC.
--
-- THIS FILE IS DATA, AND ONLY DATA. Where a flight master stands and
-- which art tiles cover an unexplored corner of Desolace are facts
-- about the game world, not decisions - there is no writing them from
-- scratch and no deriving them from the client, because the client
-- only ever reports the tiles you have ALREADY explored. The positions
-- and tile lists below were collected by Leatrix Maps
-- (curseforge.com/wow/addons/leatrix-maps) and are used here with that
-- credit. Every line of code that reads them is ZacUI's own.
--
-- Reshaped on the way in, by build/mapdata.py:
--   * pin records lost three permanently-nil vestigial fields and the
--     per-row atlas name, which is a pure function of the row's kind
--     and now lives once in Maps_Icons instead of 470 times here;
--   * reveal keys were strings ("128:110:464:33") that had to be split
--     and coerced back to numbers on every read - they are numbers;
--   * names lost their localisation wrapper, which returned the key
--     unchanged in English anyway; zone names are resolved from the
--     client at runtime instead, so they localise for free;
--   * dropped 169 pins across 15 Outland maps, which a Classic Era
--     client has no art for and never displays;
--
-- NO RECORD IN THIS FILE CONTAINS A HOLE. Optional pin fields are
-- named rather than positional precisely so that ipairs and # are
-- safe on everything here - the hole-in-ipairs trap has cost this
-- codebase two separate bugs already and it is not being invited
-- into a 1200-line data file.

